a = int(input("Первое число: "))
b = int(input("Второе число: "))
op = input("Операция (+, -, *, /): ")


if op == "+":
    result = a + b
elif op == "-":
    result = a - b
elif op == "*":
    result = a * b
elif op == "/":
    result = a / b
    if b == 0:
        print("Ошибка: деление на ноль")
else:
    print("Ошибка: недопустимая операция")

print("Результат:", result)







